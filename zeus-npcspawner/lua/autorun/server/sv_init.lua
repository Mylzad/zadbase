hook.Add("Initialize", "StartTheWorldNPCStuff", function()
	for k, v in pairs(ZADBase.NPCInfo) do
		if !(ZADBase.NPCInfo[k].WorldSpawn) then continue end
		local count = 1
		if(ZADBase.NPCInfo[k].Amount != nil) then count = ZADBase.NPCInfo[k].Amount end
		for i=1, count do
			timer.Simple(ZADBase.NPCInfo[k].Delay, function()
				ZADBase:SpawnNPC(k)
			end)
		end
	end
end)

