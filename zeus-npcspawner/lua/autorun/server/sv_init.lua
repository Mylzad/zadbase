function ZADBase:SpawnNPC(name)
	local ent = ents.Create(ZADBase.NPCInfo[name].NPC)
	ent.IsBoss = ZADBase.NPCInfo[name].Boss
	if !IsValid(ent) then return end
	if !(ZADBase.NPCInfo[name].Boss) then
		local pos = Vector(ZADBase.NPCInfo[name].Position + Vector(math.random(-250,250), math.random(-250, 250), 0))
		ent:SetPos(pos)
	else
		ent:SetPos(ZADBase.NPCInfo[name].Position)
	end
	ent.SpawnerName = name
	ent:Spawn()
	ent:SetHealth(ZADBase.NPCInfo[name].SpawnHealth)
	ent:Activate()
end

hook.Add("OnNPCKilled", "NPCJustDied", function(npc, ply)
	if(npc.SpawnerName != nil) then
		local name = npc.SpawnerName
		timer.Simple(ZADBase.NPCInfo[name].Delay, function() ZADBase:SpawnNPC(name) end)
		return
	end
end)

hook.Add( "PlayerSpawnedNPC" , "ClassifyBossCorrectlyHook" , function(ply, npc)
	for k,v in pairs(ZADBase.NPCInfo) do
		if(ZADBase.NPCInfo[k].NPC == npc:GetClass()) then
			npc.IsBoss = ZADBase.NPCInfo[k].Boss
			return
		end
	end
end)
